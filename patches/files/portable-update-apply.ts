/**
 * Portable (green build) self-update.
 *
 * This build ships as a bare `resources/app.asar` next to a stock Electron
 * binary, so there is no installer/updater helper to hand the swap to — the
 * mainstream equivalents (Squirrel's `Update.exe`, NSIS installers, AppImage)
 * all do the same thing behind a productized name: a SEPARATE process replaces
 * the files after the app exits and relaunches it.
 *
 * Flow (never writes into the running bundle itself):
 *   1. main process downloads app.asar + app.asar.unpacked.tar.gz into
 *      `resources/.portable-update/` and verifies their sha256;
 *   2. writes a platform script (sh / ps1) that waits for this pid, backs up
 *      the old asar, swaps in the new one, unpacks node-pty and restarts;
 *   3. spawns that script detached and returns, so the caller can quit.
 */
import { spawn } from 'node:child_process'
import { createHash } from 'node:crypto'
import { chmod, mkdir, readdir, rm, stat, writeFile } from 'node:fs/promises'
import { createWriteStream, existsSync } from 'node:fs'
import { join } from 'node:path'
import { Readable } from 'node:stream'
import { pipeline } from 'node:stream/promises'

export interface PortableUpdateRequest {
  /** GitHub release asset URL for app.asar. */
  asarUrl: string
  /** GitHub release asset URL for app.asar.unpacked.tar.gz. */
  unpackedUrl: string
  /** Expected sha256 of app.asar (lowercase hex). */
  sha256: string
  /** Expected sha256 of app.asar.unpacked.tar.gz. */
  unpackedSha256: string
  /** Human-readable target version, only used in the log. */
  version?: string
}

export interface PortableUpdateDeps {
  /** Elected resources dir (defaults to process.resourcesPath). */
  resourcesPath?: string
  /** Launcher to restart after the swap (defaults to the current image). */
  restartTarget?: string
  log?: (message: string) => void
}

export interface PortableUpdateResult {
  ok: boolean
  error?: 'bad-request' | 'download-failed' | 'checksum-mismatch' | 'spawn-failed'
  message?: string
  scriptPath?: string
}

// Only our own release assets: the URL arrives from the renderer, and a
// compromised renderer must not be able to make main write arbitrary bytes
// onto disk (or read from intranet hosts).
const ALLOWED_HOSTS = new Set([
  'github.com',
  'objects.githubusercontent.com',
  'release-assets.githubusercontent.com',
  'api.github.com'
])

function assertAssetUrl(url: string): URL {
  let parsed: URL

  try {
    parsed = new URL(url)
  } catch {
    throw new Error(`invalid update url: ${url}`)
  }

  if (parsed.protocol !== 'https:') {
    throw new Error(`refusing non-https update url: ${url}`)
  }

  if (!ALLOWED_HOSTS.has(parsed.hostname)) {
    throw new Error(`refusing update url from host ${parsed.hostname}`)
  }

  return parsed
}

/** Stream to disk while hashing, so a 50 MB asar never sits in memory twice. */
async function downloadAndHash(url: string, dest: string, expectedSha: string): Promise<void> {
  assertAssetUrl(url)

  const response = await fetch(url, { redirect: 'follow', signal: AbortSignal.timeout(15 * 60 * 1000) })

  if (!response.ok || !response.body) {
    throw new Error(`download failed (${response.status}) for ${url}`)
  }

  const hash = createHash('sha256')
  const body = Readable.fromWeb(response.body as Parameters<typeof Readable.fromWeb>[0])
  body.on('data', (chunk: Buffer) => hash.update(chunk))

  await pipeline(body, createWriteStream(dest))

  const got = hash.digest('hex')

  if (expectedSha && got !== expectedSha.toLowerCase()) {
    await rm(dest, { force: true })
    throw new Error(`checksum mismatch for ${url}: expected ${expectedSha}, got ${got}`)
  }
}

function shQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`
}

function psQuote(value: string): string {
  return `'${value.replace(/'/g, `''`)}'`
}

function posixScript(options: {
  resources: string
  workDir: string
  pid: number
  restartTarget: string
  version: string
}): string {
  const { resources, workDir, pid, restartTarget, version } = options

  return `#!/bin/sh
# Generated by the Hermes portable updater. Do not edit.
set -u
RES=${shQuote(resources)}
WORK=${shQuote(workDir)}
APP=${shQuote(restartTarget)}
PID=${pid}
LOG="$WORK/apply.log"
exec >>"$LOG" 2>&1

echo "[$(date -Is)] updater start (target ${version}, waiting for pid $PID)"
i=0
while kill -0 "$PID" 2>/dev/null && [ "$i" -lt 240 ]; do
  sleep 0.5
  i=$((i + 1))
done
sleep 1

if [ ! -w "$RES" ]; then
  echo "[$(date -Is)] ERROR: $RES is not writable"
  exit 1
fi

STAMP=$(date +%Y%m%d-%H%M%S)
if [ -f "$RES/app.asar" ]; then
  cp -f "$RES/app.asar" "$RES/app.asar.bak-$STAMP" || echo "warning: asar backup failed"
fi

mv -f "$WORK/app.asar.new" "$RES/app.asar" || { echo "ERROR: swapping app.asar failed"; exit 1; }

if [ -d "$RES/app.asar.unpacked" ]; then
  rm -rf "$RES/app.asar.unpacked.old-$STAMP"
  mv "$RES/app.asar.unpacked" "$RES/app.asar.unpacked.old-$STAMP" 2>/dev/null || rm -rf "$RES/app.asar.unpacked"
fi

if ! tar -xzf "$WORK/app.asar.unpacked.tar.gz.new" -C "$RES"; then
  echo "ERROR: unpacking app.asar.unpacked failed, restoring backup"
  [ -f "$RES/app.asar.bak-$STAMP" ] && cp -f "$RES/app.asar.bak-$STAMP" "$RES/app.asar"
  exit 1
fi

find "$RES/app.asar.unpacked" -name 'spawn-helper' -exec chmod 755 {} + 2>/dev/null
echo "[$(date -Is)] updated, restarting $APP"
setsid "$APP" >/dev/null 2>&1 &
exit 0
`
}

function powershellScript(options: {
  resources: string
  workDir: string
  pid: number
  restartTarget: string
  version: string
}): string {
  const { resources, workDir, pid, restartTarget, version } = options

  // PowerShell 5.1 reads a BOM-less UTF-8 script as ANSI, so the caller writes
  // this file with a UTF-8 BOM; keep the body ASCII-only to stay safe anyway.
  return `$ErrorActionPreference = 'Stop'
$res = ${psQuote(resources)}
$work = ${psQuote(workDir)}
$appExe = ${psQuote(restartTarget)}
$appPid = ${pid}
$logPath = Join-Path $work 'apply.log'

function Write-Log([string]$message) {
  "$([DateTime]::Now.ToString('s')) $message" | Out-File -LiteralPath $logPath -Append -Encoding utf8
}

Write-Log "updater start (target ${version}, waiting for pid $appPid)"

# Writing under resources\\ may need elevation (a program-files install), so
# probe first and relaunch this script through UAC once if we cannot write.
$probe = Join-Path $work 'write-probe.tmp'
try {
  [IO.File]::WriteAllText($probe, '.')
  Remove-Item -LiteralPath $probe -Force
} catch {
  Write-Log 'no write access under resources; relaunching elevated'
  Start-Process -FilePath 'powershell.exe' -Verb RunAs -ArgumentList @(
    '-NoProfile', '-ExecutionPolicy', 'Bypass', '-WindowStyle', 'Hidden', '-File', $PSCommandPath
  )
  exit 0
}

$waited = 0
while ((Get-Process -Id $appPid -ErrorAction SilentlyContinue) -and $waited -lt 240) {
  Start-Sleep -Milliseconds 500
  $waited++
}
Start-Sleep -Seconds 1

$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
$asar = Join-Path $res 'app.asar'
if (Test-Path -LiteralPath $asar) {
  Copy-Item -LiteralPath $asar -Destination (Join-Path $res "app.asar.bak-$stamp") -Force
}

Move-Item -LiteralPath (Join-Path $work 'app.asar.new') -Destination $asar -Force

$unpacked = Join-Path $res 'app.asar.unpacked'
if (Test-Path -LiteralPath $unpacked) {
  $old = "$unpacked.old-$stamp"
  if (Test-Path -LiteralPath $old) { Remove-Item -LiteralPath $old -Recurse -Force }
  Move-Item -LiteralPath $unpacked -Destination $old
}

& "$env:SystemRoot\\System32\\tar.exe" -xzf (Join-Path $work 'app.asar.unpacked.tar.gz.new') -C $res
if ($LASTEXITCODE -ne 0) {
  Write-Log 'ERROR: unpacking app.asar.unpacked failed, restoring backup'
  if (Test-Path -LiteralPath (Join-Path $res "app.asar.bak-$stamp")) {
    Copy-Item -LiteralPath (Join-Path $res "app.asar.bak-$stamp") -Destination $asar -Force
  }
  exit 1
}

Write-Log 'updated, restarting'
Start-Process -FilePath $appExe
exit 0
`
}

/** Launcher to start after the swap: the packaged app's own image. */
function defaultRestartTarget(): string {
  // Linux installs drop a launcher in /usr/bin that carries the right
  // flags (ozone platform etc.); prefer it when present.
  if (process.platform === 'linux' && existsSync('/usr/bin/hermes-desktop')) {
    return '/usr/bin/hermes-desktop'
  }

  return process.execPath
}

/**
 * Downloads, verifies, and starts the detached updater. Resolves once the
 * helper is spawned — the caller is expected to quit the app right after.
 */
export async function applyPortableUpdate(
  request: PortableUpdateRequest,
  deps: PortableUpdateDeps = {}
): Promise<PortableUpdateResult> {
  const log = deps.log ?? (message => console.warn(`[portable-update] ${message}`))

  try {
    assertAssetUrl(request.asarUrl)
    assertAssetUrl(request.unpackedUrl)
  } catch (error) {
    return { ok: false, error: 'bad-request', message: (error as Error).message }
  }

  const resources = deps.resourcesPath ?? process.resourcesPath
  const workDir = join(resources, '.portable-update')
  const restartTarget = deps.restartTarget ?? defaultRestartTarget()

  try {
    await mkdir(workDir, { recursive: true })
    log(`downloading ${request.version ?? ''} asar`)
    await downloadAndHash(request.asarUrl, join(workDir, 'app.asar.new'), request.sha256)
    log('downloading unpacked archive')
    await downloadAndHash(request.unpackedUrl, join(workDir, 'app.asar.unpacked.tar.gz.new'), request.unpackedSha256)
  } catch (error) {
    const message = (error as Error).message
    log(`download failed: ${message}`)

    return {
      ok: false,
      error: message.includes('checksum') ? 'checksum-mismatch' : 'download-failed',
      message
    }
  }

  const isWindows = process.platform === 'win32'
  const scriptPath = join(workDir, isWindows ? 'apply-update.ps1' : 'apply-update.sh')
  const body = isWindows
    ? powershellScript({ resources, workDir, pid: process.pid, restartTarget, version: request.version ?? '' })
    : posixScript({ resources, workDir, pid: process.pid, restartTarget, version: request.version ?? '' })

  try {
    if (isWindows) {
      // UTF-8 with BOM: Windows PowerShell 5.1 otherwise parses the file as ANSI.
      await writeFile(scriptPath, `\ufeff${body}`, 'utf8')
    } else {
      await writeFile(scriptPath, body, { encoding: 'utf8', mode: 0o755 })
      await chmod(scriptPath, 0o755)
    }
  } catch (error) {
    return { ok: false, error: 'spawn-failed', message: (error as Error).message }
  }

  try {
    const child = isWindows
      ? spawn(
          'powershell.exe',
          ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-WindowStyle', 'Hidden', '-File', scriptPath],
          { detached: true, stdio: 'ignore', windowsHide: true }
        )
      : spawn('/bin/sh', [scriptPath], { detached: true, stdio: 'ignore' })

    child.on('error', error => log(`spawning updater failed: ${error.message}`))
    child.unref()
  } catch (error) {
    return { ok: false, error: 'spawn-failed', message: (error as Error).message }
  }

  log(`updater spawned: ${scriptPath}`)

  return { ok: true, scriptPath }
}

/** Housekeeping: drop backups older than the newest two, plus stale work dirs. */
export async function prunePortableUpdateBackups(resourcesPath = process.resourcesPath): Promise<void> {
  const entries = await readdir(resourcesPath).catch(() => [] as string[])

  for (const prefix of ['app.asar.bak-', 'app.asar.unpacked.old-']) {
    const matching = entries.filter(name => name.startsWith(prefix)).sort()

    for (const stale of matching.slice(0, Math.max(0, matching.length - 2))) {
      await rm(join(resourcesPath, stale), { recursive: true, force: true }).catch(() => undefined)
    }
  }

  const workDir = join(resourcesPath, '.portable-update')

  for (const name of ['app.asar.new', 'app.asar.unpacked.tar.gz.new']) {
    const full = join(workDir, name)
    const info = await stat(full).catch(() => null)

    // Leftovers from a run that never reached the helper (or a failed attempt).
    if (info && Date.now() - info.mtimeMs > 6 * 60 * 60 * 1000) {
      await rm(full, { force: true }).catch(() => undefined)
    }
  }
}

